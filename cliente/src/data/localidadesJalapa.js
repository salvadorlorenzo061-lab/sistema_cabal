export const normalizarLocalidadesJalapa = (extras = []) => {
  const mapa = new Map();

  [...LOCALIDADES_JALAPA_BASE, ...extras].forEach((item) => {
    const nombre = (item?.nombre || item?.nombre_comunidad || '').trim();
    if (!nombre) return;

    const tipo = (item?.tipo || '').trim().toLowerCase();
    const parent = (item?.parent || '').trim();
    const llave = `${nombre.toLowerCase()}|${tipo}|${parent.toLowerCase()}`;

    if (!mapa.has(llave)) {
      mapa.set(llave, {
        nombre,
        tipo,
        parent,
        searchText: `${nombre} ${tipo} ${parent}`.toLowerCase()
      });
    }
  });

  return Array.from(mapa.values()).sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'));
};
